outLines.push('');
outLines.push('module font8x8 (');
outLines.push('    input  wire [6:0] i_char,   // ASCII 码（7 位）');
outLines.push('    input  wire [2:0] i_row,    // 字形行 0..7（0 = 顶部）');
outLines.push('    output reg  [7:0] o_row     // bit7 = 最左像素');
