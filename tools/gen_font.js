for (const ch of ordered) {
  const code = ch.charCodeAt(0);
  const rows = FONT[ch];
  rows.forEach((hex, r) => {
    outLines.push(`            {7'h${code.toString(16).padStart(2, '0')}, 3'd${r}}: o_row = 8'h${hex};`);
  });
}

